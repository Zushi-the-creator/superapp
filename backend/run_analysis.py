# Live prices (from Alpha Vantage)
live_prices = {"VST": 172.58, "LLY": 1063.56, "MRVL": 83.22}

portfolio = {
    "VST": {"shares": 7.9038, "avg_entry": 169.58},
    "LLY": {"shares": 1, "avg_entry": 1080.50},
    "MRVL": {"shares": 9, "avg_entry": 86.50}
}

def main():
    selector = HybridModelSelector()

    print("="*70)
    print("PORTFOLIO ANALYSIS - FIXED MODELS WITH REGIME FILTER")
    print("Date: 2026-01-13")
    print("="*70)

    total_cost = 0
    total_value = 0
    recommendations = []

    for ticker in ["VST", "LLY", "MRVL"]:
        pos = portfolio[ticker]
        closes = historical[ticker]["closes"] + [live_prices[ticker]]
        volumes = historical[ticker]["volumes"] + [historical[ticker]["volumes"][-1]]
        current_price = live_prices[ticker]

        print(f"\n{ticker} (LIVE): ${current_price}")
        print("-" * 50)

        best_model, accuracy, all_results = selector.find_best_model(ticker, closes, volumes)
        signal = selector.get_signal(ticker, closes, volumes, auto_select=False)

        entry = pos["avg_entry"]
        shares = pos["shares"]
        pnl = (current_price - entry) * shares
        pnl_pct = ((current_price - entry) / entry) * 100
        cost = entry * shares
        value = current_price * shares

        total_cost += cost
        total_value += value

        print(f"  Position: {shares} shares @ ${entry} = ${cost:.2f}")
        print(f"  Current:  ${current_price} x {shares} = ${value:.2f}")
        print(f"  P&L:      ${pnl:+.2f} ({pnl_pct:+.2f}%)")
        print()
        print(f"  BEST MODEL: {best_model}")
        print(f"  Win Rate:   {accuracy}%")
        print(f"  SIGNAL:     {signal.signal} (strength: {signal.strength})")

        ind = signal.indicators
        print(f"  Regime:     {ind.get('Regime', 'N/A')}")
        if "Blocked" in ind:
            print(f"  >>> {ind['Blocked']} <<<")

        print(f"  Indicators:")
        for k, v in ind.items():
            if k not in ["Regime", "Blocked", "above_SMA50", "above_SMA200"]:
                print(f"    {k}: {v}")

        recommendations.append({
            "ticker": ticker,
            "signal": signal.signal,
            "strength": signal.strength,
            "pnl_pct": pnl_pct,
            "regime": ind.get("Regime", "N/A"),
            "blocked": ind.get("Blocked")
        })

    total_pnl = total_value - total_cost
    total_pnl_pct = (total_pnl / total_cost) * 100
    monthly_target = total_cost * 0.01

    print(f"\n{'='*70}")
    print("PORTFOLIO SUMMARY")
    print(f"{'='*70}")
    print(f"Cost Basis:      ${total_cost:,.2f}")
    print(f"Current Value:   ${total_value:,.2f}")
    print(f"Total P&L:       ${total_pnl:+,.2f} ({total_pnl_pct:+.2f}%)")
    print()
    print(f"Monthly Target:  ${monthly_target:.2f} (1%)")
    if total_pnl >= monthly_target:
        print(f"STATUS:          TARGET MET!")
    else:
        print(f"Gap to Target:   ${monthly_target - total_pnl:.2f}")

    print(f"\n{'='*70}")
    print("ACTIONABLE RECOMMENDATIONS")
    print(f"{'='*70}")
    for rec in recommendations:
        print(f"\n{rec['ticker']}:")
        if rec["blocked"]:
            print(f"  Action: HOLD (blocked by regime filter)")
            print(f"  Reason: {rec['blocked']}")
        elif rec["signal"] == "BUY":
            print(f"  Action: ADD to position")
            print(f"  Signal: {rec['signal']} ({rec['strength']}% confidence)")
        elif rec["signal"] == "SELL":
            print(f"  Action: REDUCE/EXIT position")
            print(f"  Signal: {rec['signal']} ({rec['strength']}% confidence)")
        else:
            print(f"  Action: HOLD current position")
            print(f"  Signal: No clear direction")
        print(f"  Current P&L: {rec['pnl_pct']:+.2f}%")

if __name__ == "__main__":
    main()
